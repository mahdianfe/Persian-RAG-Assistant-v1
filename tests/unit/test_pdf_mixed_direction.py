from app.services.pdf_reconstruction import (
    PDFReconstructionService,
)
from app.services.pdf_structure import (
    PDFCharacter,
    PDFLine,
)


def make_character(
    text: str,
    x0: float,
    x1: float,
) -> PDFCharacter:
    """Create a PDF character for reconstruction tests."""

    return PDFCharacter(
        text=text,
        x0=x0,
        y0=130.0,
        x1=x1,
        y1=144.0,
        font_name="ArialMT",
        font_size=12.0,
    )


