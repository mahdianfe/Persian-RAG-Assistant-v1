class RAGPrompt:
    """Build grounded prompts for retrieval-augmented generation."""

    @staticmethod
    def build(
        question: str,
        context: str,
    ) -> str:
        """Build a strict context-grounded prompt."""

        return f"""
تو یک دستیار پرسش و پاسخ فارسی هستی.

وظیفه:
به سؤال کاربر فقط و فقط بر اساس اطلاعات صریح موجود در CONTEXT پاسخ بده.

قوانین:
1. از هیچ اطلاعاتی خارج از CONTEXT استفاده نکن.
2. حدس، تفسیر، استنباط، دانش عمومی و تکمیل اطلاعات ممنوع است.
3. فقط اطلاعاتی را بیان کن که مستقیماً در CONTEXT آمده‌اند.
4. اگر پاسخ سؤال در CONTEXT وجود ندارد یا اطلاعات کافی برای پاسخ وجود ندارد، دقیقاً بنویس:
«پاسخ این سؤال در اسناد موجود پیدا نشد.»
5. اگر فقط بخشی از پاسخ در CONTEXT وجود دارد، فقط همان بخش را بیان کن.
6. مثال یا توضیح جدید اضافه نکن، مگر اینکه صریحاً در CONTEXT آمده باشد.
7. سؤال را تکرار نکن.
8. درباره CONTEXT، retrieval، embedding، مدل یا فرآیند داخلی سیستم صحبت نکن.
9. پاسخ را کوتاه، مستقیم و فقط به زبان فارسی بنویس.
10. فقط پاسخ نهایی را ارائه کن.

CONTEXT:
{context}

QUESTION:
{question}

پاسخ:
""".strip()
