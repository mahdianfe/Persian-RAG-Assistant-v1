class RAGPrompt:
    """Build strict extraction prompts for RAG."""

    @staticmethod
    def build(
        question: str,
        context: str,
    ) -> str:

        return f"""
تو یک موتور استخراج متن هستی.

فقط از CONTEXT استفاده کن.
قوانین قطعی:

- از دانش قبلی خود استفاده نکن.
- هیچ توضیحی اضافه نکن.
- هیچ تعریف، مثال یا تفسیر ننویس.
- معنی کلمات را توضیح نده.
- متن جدید تولید نکن.
- اگر چیزی در CONTEXT نیست، آن را ننویس.

برای سؤال‌های لیستی:
فقط همان موارد موجود در متن را خط به خط استخراج کن.

برای سؤال‌های واژه‌ها:
فقط خود واژه‌ها را بنویس.

برای مثال:
اگر در متن آمده:
Python ، RAG ، PDF

خروجی باید فقط باشد:

Python
RAG
PDF

نه بیشتر.

اگر پاسخ وجود ندارد فقط بنویس:

پاسخ این سؤال در اسناد موجود پیدا نشد.

CONTEXT:
{context}

QUESTION:
{question}

ANSWER:
""".strip()
